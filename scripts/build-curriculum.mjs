// Generate src/data/curriculum.ts from the curriculum database.
//
//   node scripts/build-lesson-db.mjs && node scripts/build-curriculum.mjs
//
// This replaces the sitemap-derived build. The sitemaps could only give titles,
// slugs and video ids, with module membership guessed from lesson codes and
// Grade 3 missing entirely because its lessons are coded BG-15xx rather than
// B3-xxx. The database has the site's own answer for all of it: which module a
// lesson belongs to, in what order it is taught, and which grade it sits at.
//
// Structure only. Lesson bodies stay in curriculum/justinguitar.db.json,
// outside src/, so they cannot reach a bundle.
//
// Every course ships, not just the graded path. It is a lazily-loaded chunk,
// and trimming it would mean a learner whose current lesson sits outside the
// eight graded courses silently gets someone else's Journey. Runtimes are left
// out because nothing reads them yet; they are in the database when something
// does.

import { readFileSync, writeFileSync } from 'node:fs';

const DB = 'curriculum/justinguitar.db.json';
const OUT = 'src/data/curriculum.ts';

const db = JSON.parse(readFileSync(DB, 'utf8'));

// Courses the site itself presents as superseded. Kept in the data, flagged so
// a picker can put them behind the current ones rather than beside them.
const LEGACY = /\[CLASSIC\]|^Old /i;

const lessons = [];
const tracks = [];

for (const course of db.courses) {
  const code = course.reference.toLowerCase();
  const modules = [];

  course.modules.forEach((mod) => {
    // A module the course numbers is part of the taught path. A module it names
    // instead is a companion series that runs alongside it: Justin's own
    // left-handed practice log sits under Grade 1 but appears nowhere on the
    // Grade 1 class page. Inventing a number for those put 37 practice videos
    // into the middle of the teaching spine.
    const number = mod.number;
    const slugs = [];

    mod.lessons.forEach((lesson, i) => {
      // A paid lesson is real and holds its place in the order, but we have no
      // reference code for it and nothing to teach from. It stays counted in
      // lessonCount and out of here, which is what keeps the module honest.
      if (lesson.status !== 'ok') return;
      slugs.push(lesson.slug);
      lessons.push({
        slug: lesson.slug,
        track: code,
        code: lesson.reference.toLowerCase(),
        module: number,
        position: i + 1,
        title: lesson.title,
        ...(lesson.video ? { videoId: lesson.video } : {}),
      });
    });

    modules.push({
      number,
      companion: number === null,
      reference: mod.reference,
      title: mod.title,
      grade: mod.grade,
      lessonCount: mod.lessonCount,
      paidNotListed: mod.paidNotListed,
      lessons: slugs,
    });
  });

  tracks.push({
    code,
    title: course.title,
    grades: course.grades,
    order: course.grades[0] ?? null,
    legacy: LEGACY.test(course.title),
    modules,
  });
}

const curriculum = {
  source: {
    site: 'https://www.justinguitar.com',
    files: [DB],
    note: "Each lesson page publishes its own content as JSON; this is the site's own "
      + 'module membership, taught order and grade, not inferred from lesson codes.',
    builtAt: new Date().toISOString().slice(0, 10),
  },
  counts: {
    tracks: tracks.length,
    modules: tracks.reduce((n, t) => n + t.modules.length, 0),
    lessons: lessons.length,
    paidNotListed: db.counts.paidNotListed,
  },
  tracks,
  lessons,
};

const file = `// GENERATED by scripts/build-curriculum.mjs. Do not edit by hand.
//
// Structure only: titles, codes, grades, ordering, links. The lesson bodies
// live in curriculum/justinguitar.db.json, outside src/, so they cannot reach
// a bundle. See curriculum/README.md.

/** Where a lesson lives on the course site. */
export const LESSON_BASE = 'https://www.justinguitar.com/guitar-lessons/';

export interface CurriculumLesson {
  slug: string;
  /** Course code this lesson belongs to, e.g. 'bg1'. */
  track: string;
  /** The site's own lesson code, e.g. 'b1-403'. Authoritative for ordering. */
  code: string;
  /** Null when the lesson sits in a companion series rather than a numbered module. */
  module: number | null;
  position: number;
  title: string;
  /** YouTube id of the lesson video, where the course names one. */
  videoId?: string;
}

export const lessonUrl = (lesson: CurriculumLesson): string => LESSON_BASE + lesson.slug;

export interface CurriculumModule {
  /** Null for a companion series the course names rather than numbers. */
  number: number | null;
  /** Runs alongside the taught path rather than being part of it. */
  companion: boolean;
  /** The course's own module code, e.g. 'BG04'. */
  reference: string;
  title: string;
  /** Null only where a module genuinely spans more than one grade. */
  grade: number | null;
  /** Every lesson in the module, including any we cannot read. */
  lessonCount: number;
  /** How many of those are paid, and so absent from \`lessons\` below. */
  paidNotListed: number;
  lessons: string[];
}

export interface CurriculumTrack {
  code: string;
  title: string;
  /** A course can span grades; the classic beginner course spans three. */
  grades: number[];
  order: number | null;
  legacy: boolean;
  modules: CurriculumModule[];
}

export interface Curriculum {
  source: { site: string; files: string[]; note: string; builtAt: string };
  counts: { tracks: number; modules: number; lessons: number; paidNotListed: number };
  tracks: CurriculumTrack[];
  lessons: CurriculumLesson[];
}

// Not \`as const\`: it would mint thousands of literal types for no gain and
// make every consumer fight the checker to pass a plain string.
export const CURRICULUM: Curriculum = ${JSON.stringify(curriculum, null, 2)};

const BY_SLUG = new Map(CURRICULUM.lessons.map((l) => [l.slug, l]));
const BY_CODE = new Map(CURRICULUM.lessons.map((l) => [l.code, l]));

export const getLesson = (slug: string): CurriculumLesson | null => BY_SLUG.get(slug) ?? null;
export const getLessonByCode = (code: string): CurriculumLesson | null => BY_CODE.get(code) ?? null;
export const getTrack = (code: string): CurriculumTrack | null =>
  CURRICULUM.tracks.find((t) => t.code === code) ?? null;

/**
 * The course a lesson code belongs to.
 *
 * Splitting the code on its first dash used to answer this, and it was wrong
 * for every Grade 2 and Grade 3 lesson: those are coded BG-1501, so the split
 * returned 'bg' and matched no course at all. Ask the lesson instead.
 */
export const trackOfLesson = (code: string): string | null =>
  BY_CODE.get(code)?.track ?? null;

/** A track's modules with their lessons resolved, in taught order. */
export function trackModules(
  code: string,
): Array<{ number: number | null; companion: boolean; reference: string; title: string; grade: number | null; lessons: CurriculumLesson[] }> {
  const track = getTrack(code);
  if (!track) return [];
  return track.modules.map((m) => ({
    number: m.number,
    companion: m.companion,
    reference: m.reference,
    title: m.title,
    grade: m.grade,
    lessons: m.lessons.map(getLesson).filter((l): l is CurriculumLesson => l !== null),
  }));
}
`;

writeFileSync(OUT, file);
console.log(`\n${OUT}`);
console.log(`  ${curriculum.counts.tracks} courses, ${curriculum.counts.modules} modules, `
  + `${curriculum.counts.lessons} lessons, ${curriculum.counts.paidNotListed} paid and unlisted\n`);
for (const t of tracks.filter((x) => !x.legacy && x.grades[0] > 0)) {
  console.log(`  ${t.code.padEnd(6)} grades ${t.grades.join('/').padEnd(8)} ${String(t.modules.length).padStart(3)} modules  ${t.title}`);
}
console.log('');
